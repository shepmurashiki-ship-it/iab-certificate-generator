-- 001 — Secure public certificate verification and least-privilege grants.
-- Idempotent: safe to run more than once. Run as the postgres role (SQL editor / supabase db query).
-- Changes ONLY:
--   * certificates.verification_token   new nullable column (random per-certificate token carried in the QR URL)
--   * verify_certificate(text, text)     replaces verify_certificate(text): validated, exact, minimal output
--   * EXECUTE grants on the public functions
--   * anon / authenticated table privileges (anon: none; authenticated: no TRUNCATE/REFERENCES/TRIGGER/MAINTAIN)
-- No rows are read, written or deleted. RLS policies are unchanged.
-- Rollback: 001_secure_public_verification.rollback.sql

-- 1. Verification token: 128-bit random, base64url, generated by the issuing client, readable only by staff (RLS).
alter table public.certificates add column if not exists verification_token text;
do $$ begin
  if not exists (select 1 from pg_constraint where conname = 'certificates_verification_token_format'
                 and conrelid = 'public.certificates'::regclass) then
    alter table public.certificates add constraint certificates_verification_token_format
      check (verification_token is null or verification_token ~ '^[A-Za-z0-9_-]{22,64}$');
  end if;
end $$;

-- 2. Public verification endpoint.
--    Exact lookup of one validated reference. Draft / failed certificates are never visible.
--    With the matching token (QR code): full public detail incl. learner name.
--    Reference only (typed in, or legacy QR without token): limited detail — learner initials, no full name.
--    Wrong token, unknown, malformed or wildcard input: {"result":"not_found"}. Internal errors: {"result":"error"}.
drop function if exists public.verify_certificate(text);
create or replace function public.verify_certificate(p_reference text, p_token text default null)
returns jsonb
language plpgsql stable security definer
set search_path = ''
as $$
declare
  v_ref  text := upper(btrim(coalesce(p_reference, '')));
  v_tok  text := btrim(coalesce(p_token, ''));
  v_full boolean := false;
  v_initials text;
  c record;
begin
  if length(v_ref) > 40
     or v_ref !~ '^IAB/CERT/[A-Z]{2,8}/[0-9]{4}(JAN|FEB|MAR|APR|MAY|JUN|JUL|AUG|SEP|OCT|NOV|DEC)/[0-9]{6}/[0-9]{4}(-R[0-9]{1,3})?$' then
    return jsonb_build_object('result', 'not_found');
  end if;
  if v_tok <> '' and v_tok !~ '^[A-Za-z0-9_-]{22,64}$' then
    return jsonb_build_object('result', 'not_found');
  end if;

  select x.certificate_reference, x.full_name_at_issue, x.course_name_at_issue, x.award_date, x.issue_date,
         x.status::text as status, x.verification_token
    into c
    from public.certificates x
   where x.certificate_reference = v_ref
     and x.status in ('Issued', 'Superseded', 'Revoked');
  if not found then
    return jsonb_build_object('result', 'not_found');
  end if;

  if v_tok <> '' then
    if c.verification_token is null or c.verification_token <> v_tok then
      return jsonb_build_object('result', 'not_found');
    end if;
    v_full := true;
  else
    select string_agg(left(w, 1) || '.', ' ') into v_initials
      from regexp_split_to_table(btrim(c.full_name_at_issue), '\s+') as w where w <> '';
  end if;

  return jsonb_build_object(
    'result', 'found',
    'detail', case when v_full then 'full' else 'limited' end,
    'certificate_reference', c.certificate_reference,
    'status', c.status,
    'course', c.course_name_at_issue,
    'award_date', c.award_date,
    'issue_date', c.issue_date,
    'learner_name', case when v_full then c.full_name_at_issue end,
    'learner_initials', case when v_full then null else v_initials end
  );
exception when others then
  return jsonb_build_object('result', 'error');
end;
$$;

revoke all on function public.verify_certificate(text, text) from public;
grant execute on function public.verify_certificate(text, text) to anon, authenticated, service_role;

-- 3. Reference allocation is staff-only (the function also checks the staff role itself).
revoke all on function public.reserve_certificate_reference(text, integer, text, date) from public, anon;
grant execute on function public.reserve_certificate_reference(text, integer, text, date) to authenticated, service_role;

-- current_staff_role() keeps its grants: RLS policies call it for every role, and for anon it returns null.

-- 4. Table privileges. anon reaches data only through verify_certificate(); RLS stays the row-level gate for staff.
revoke all on table
  public.staff_profiles, public.courses, public.learners, public.import_batches,
  public.reference_counters, public.certificates, public.certificate_events, public.application_settings
  from anon;
revoke truncate, references, trigger, maintain on table
  public.staff_profiles, public.courses, public.learners, public.import_batches,
  public.reference_counters, public.certificates, public.certificate_events, public.application_settings
  from authenticated;
